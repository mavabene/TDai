
(********************** Declaration ****************************)
(* This message gets written upon crimping 	 *)
METHOD writeFoundationAsBuiltMessage : BOOL
VAR_INPUT
	CRIMPED: BOOL;
END_VAR

(********************** Implementation ****************************)
DATA := 'GPS_AB, ';
IF CRIMPED THEN
	DATA := CONCAT(DATA, 'Crimped, ');
	IF WAS_CRIMPED_IN_AUTO THEN
		DATA := CONCAT(DATA, 'AUTO, ');
	ELSE
		DATA := CONCAT(DATA, 'MANUAL, ');
	END_IF
ELSE
	DATA := CONCAT(DATA, 'Located, ');
	DATA := CONCAT(DATA, 'NA, ');
END_IF

DATA := CONCAT(DATA, TO_STRING(GPS_AXES[GPS_HEADING].OFFSET));
DATA := CONCAT(DATA, ', ');
DATA := CONCAT(DATA, TO_STRING(GPS_AXES[GPS_X].OFFSET));
DATA := CONCAT(DATA, ', ');
DATA := CONCAT(DATA, TO_STRING(GPS_AXES[GPS_Y].OFFSET));
DATA := CONCAT(DATA, ', ');
DATA := CONCAT(DATA, TO_STRING(GPS_AXES[GPS_Z].OFFSET));
DATA := CONCAT(DATA, ', ');
DATA := CONCAT(DATA, TO_STRING(MAST_PITCH_TRANSMIT));
DATA := CONCAT(DATA, ', ');
DATA := CONCAT(DATA, TO_STRING(ROTATOR_ANGLE));
DATA := CONCAT(DATA, ', ');
DATA := CONCAT(DATA, TO_STRING(GPS_RWP_CYCLE_TIME));
DATA := CONCAT(DATA, ', ');
DATA := CONCAT(DATA, TO_STRING(GPS_HRMS));
DATA := CONCAT(DATA, ', ');
DATA := CONCAT(DATA, TO_STRING(GPS_VRMS));
DATA := CONCAT(DATA, ', ');
DATA := CONCAT(DATA, TO_STRING(GPS_PDOP));
DATA := CONCAT(DATA, ', ');
DATA := CONCAT(DATA, TO_STRING(GPS_RTK_SIGNAL_DELAY));
DATA := CONCAT(DATA, ', ');
DATA := CONCAT(DATA, TO_STRING(GPS_NUM_SAT));
DATA := CONCAT(DATA, '$R$N');
write(FH := FH_GPS_AB);
